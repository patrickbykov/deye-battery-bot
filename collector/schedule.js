// Стеля відступу. Вона свідомо менша за ліміт несвіжості health-check
// (15 хв): інакше Fly перезапускав би колектор раніше, ніж той сам зробить
// чергову спробу, і причина падіння ніколи б не проявилась у логах.
const MAX_BACKOFF_MS = 600_000;

// Скорочений інтервал робить колектор чутливішим до відмов Deye: там, де
// раз на 5 хв була одна спроба, тепер їх понад три. Якщо хмара відмовляє
// через ліміти, рівний каданс лише погіршує становище — тому пауза росте,
// поки цикл падає, і повертається до звичайної одразу після успіху.
export function nextDelayMs({ intervalMs, failures }) {
  const cap = Math.max(MAX_BACKOFF_MS, intervalMs);
  return Math.min(intervalMs * 2 ** failures, cap);
}
